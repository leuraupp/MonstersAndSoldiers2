# accented letters: base glyph + mark rows above / tail below
ACCENTS = {"É": ("E", "..#.."), "Ó": ("O", "..#.."), "Á": ("A", "..#.."),
           "Õ": ("O", ".#.#."), "Ã": ("A", ".#.#."), "Ê": ("E", ".#.#.")}
CEDILLA = {"Ç": "C"}

W, H = 5, 7


def glyph(ch):
    """Returns (rows, extra_top, extra_bottom)."""
    if ch in GLYPHS:
        return GLYPHS[ch], 0, 0
    if ch in ACCENTS:
        base, mark = ACCENTS[ch]
        return [mark] + GLYPHS[base], 1, 0  # mark sits in the line above
    if ch in CEDILLA:
        return GLYPHS[CEDILLA[ch]] + ["..#.."], 0, 1
    raise KeyError(ch)


def text_width(s, spacing=1, scale=1):
    return (len(s) * (W + spacing) - spacing) * scale


def draw_text(cv, s, x, y, fill, scale=1, spacing=1, shade=None):
    """Draws `s` with its cap line at y. fill(gx, gy) -> RGBA lets callers shade
    glyphs (gy runs 0..H-1 from cap line to baseline)."""
    cx = x
    for ch in s:
        rows, top, _ = glyph(ch)
        for r, row in enumerate(rows):
            gy = r - top
            for c, v in enumerate(row):
                if v == "#":
                    col = fill(c, gy) if callable(fill) else fill
                    for a in range(scale):
                        for b in range(scale):
                            cv.set(cx + c * scale + a, y + gy * scale + b, col)
        cx += (W + spacing) * scale
    return cx
